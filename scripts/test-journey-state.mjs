import assert from 'node:assert/strict';
import { journeyOffer, journeySteps, offerDismissed } from '../src/ui/journey-state.js';

const guest = { resolved: true, signedIn: false };
const free = { resolved: true, signedIn: true, plan: 'free', limits: { serverReviewsPerDay: 3 }, usage: { serverReviews: 0 } };
assert.equal(journeyOffer({ ...guest, resolved: false }), null);
assert.equal(journeyOffer({ ...guest, blocked: true }), null);
assert.equal(journeyOffer(guest).kind, 'signup');
assert.equal(journeyOffer(guest, 'review'), null);
assert.equal(journeyOffer({ ...guest, reviewReady: true }, 'review').href, '/signup?src=review&quick=1');
assert.equal(journeyOffer(guest, 'puzzles'), null);
assert.equal(journeyOffer({ ...guest, puzzleSolved: true }, 'puzzles').kind, 'signup');
assert.equal(journeyOffer(free), null, 'new accounts practice before an upgrade prompt');
assert.equal(journeyOffer({ ...free, plan: undefined, reviewReady: true }), null, 'unknown subscription never becomes Free');
assert.equal(journeyOffer({ ...free, reviewReady: true }, 'review').tier, 'Boost');
assert.equal(journeyOffer({ ...free, usage: { serverReviews: 2 } }).tier, 'Boost');
assert.match(journeyOffer({ ...free, usage: { serverReviews: 2 } }).proof, /^2 of 3/);
assert.equal(journeyOffer({ ...free, limits: { serverReviewsPerDay: 1 } }), null, 'zero use is not near a one-review allowance');
assert.equal(journeyOffer({ ...free, progress: { review: true }, usage: {} }).proof, '', 'missing usage is never invented');
assert.equal(journeyOffer({ ...free, reviewReady: true, features: { serverReviews: false } }), null);
assert.equal(journeyOffer({ ...free, reviewReady: true, limits: { serverReviewsPerDay: null } }), null, 'unlimited account override already supplies the benefit');
assert.equal(journeyOffer({ ...free, usage: { coachUsagePercent: 79 } }, 'coach'), null);
assert.equal(journeyOffer({ ...free, usage: { coachUsagePercent: 80 } }, 'coach').tier, 'Boost');
assert.equal(journeyOffer({ ...free, plan: 'boost', usage: { coachUsagePercent: 80 } }, 'coach').tier, 'Max');
assert.equal(journeyOffer({ ...free, plan: 'max', usage: { coachUsagePercent: 100 }, reviewReady: true }), null);
assert.equal(journeyOffer({ ...free, plan: 'boost', reviewReady: true }, 'review'), null, 'Boost already includes unlimited reviews');
assert.equal(journeyOffer({ ...free, usage: { coachUsagePercent: 100 }, features: { coach: false } }, 'coach'), null);
assert.equal(journeyOffer({ ...free, puzzleSolved: true, progress: { puzzle: true } }, 'puzzles'), null, 'puzzles remain free');
assert.deepEqual(journeySteps(true).map(step => step.done), [true, false, false]);
assert.deepEqual(journeySteps(true, { review: true }, 3).map(step => step.done), [true, true, true]);
assert.equal(offerDismissed(Date.now() + 1000), true);
assert.equal(offerDismissed(Date.now() - 1000), false);
assert.equal(offerDismissed('forever'), false);
assert.equal(offerDismissed(Date.now() + 48 * 60 * 60 * 1000), false);
console.log('PASS 29 journey checks: guest signup, earned upgrades, verified plans, actual usage, feature overrides, progress, and dismissal expiry');
